"""Inspect rays in the original source, without saving or changing the master."""
import bpy, json
from pathlib import Path
from mathutils import Matrix, Vector
root=Path('D:/VYREN/06_WEBSITE'); scene=bpy.context.scene; scene.frame_set(1)
cam=bpy.data.objects['CAM_HERO']
watch=set(bpy.data.objects['WATCH_ROOT'].children_recursive)
for obj in scene.objects:
    if obj.type in ('MESH','CURVE','FONT') and (obj.hide_render or obj not in watch):obj.hide_set(True)
graph=bpy.context.evaluated_depsgraph_get()
manifest=json.loads((root/'public/assets/studio-cycles/manifest.json').read_text())
points=[Vector((.023,0,0)),Vector((0,.005,.0015)),Vector((-.0066,-.0065,.0007)),Vector((0,-.021,-.003))]
results=[]
for frame in manifest['frames']:
    cam.matrix_world=Matrix(frame['cameraMatrix']); bpy.context.view_layer.update(); hits=[]
    for p in points:
        origin=cam.matrix_world.translation.copy(); direction=(p-origin).normalized(); skipped=[]
        for attempt in range(12):
            hit,loc,normal,index,obj,matrix=scene.ray_cast(graph,origin,direction,distance=1)
            if not hit: break
            glass=any(slot.material and ('SAPPHIRE' in slot.material.name.upper() or 'CRYSTAL' in slot.material.name.upper()) for slot in obj.material_slots)
            if glass: skipped.append(obj.name); origin=loc+direction*.00001; continue
            break
        hits.append({'object':obj.name if hit else None,'targetDistance':(loc-p).length if hit else None,'glassSkipped':skipped})
    results.append({'frame':frame['frame'],'frontVisible':cam.location.z>.05,'hits':hits})
(root/'qa/phase3-1/hotspot-rays.json').write_text(json.dumps({'source':bpy.data.filepath,'savedBlend':False,'frames':results},indent=2))
allowed=[('crown_',),('dial_','hand_','hour_','minute_','logo_'),('balance_','hairspring','bridge_','escapement_'),('strap_lower','lug_','case_main')]
masks=[]
for frame in results:
    masks.append(sum(1<<i for i,hit in enumerate(frame['hits']) if hit['object'] and hit['object'].startswith(allowed[i])))
(root/'src/lib/studio-hotspot-visibility.ts').write_text('// Source ray casts through genuine sapphire; opaque occluders hide individual pins.\n// Generated by scripts/phase31-hotspots.py without saving the Blender master.\nexport const STUDIO_HOTSPOT_MASKS = '+json.dumps(masks)+';\n')
print('Read-only source ray inspection complete')
